from typing import Any, Dict, List, Protocol
from uuid import UUID

class ModelRepository(Protocol):
    async def create_model(self, name: str, model_file_path: str | None = None) -> UUID: ...
    async def get_model_by_name(self, name: str) -> Dict[str, Any] | None: ...
    async def get_model_by_id(self, model_id: UUID) -> Dict[int, Any] | None: ...
    async def delete_model(self, model_id: UUID) -> bool: ... 
    async def get_all_models_with_experiment_count(self) -> List[Dict[str, Any]]: ...

class ExperimentRepository(Protocol):
    async def log_experiment(
        self, model_id: UUID, name: str, params: Dict[str, Any],
        metrics: Dict[str, Any], model_file_path: str | None = None
    ) -> int: ...
    async def get_all_experiments(self) -> List[Dict[str, Any]]: ...